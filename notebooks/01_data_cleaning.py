import pandas as pd

url = "https://raw.githubusercontent.com/usd-tenaalshaikhli/AAI501-Team3-Ecommerce-Churn/main/data/E%20Commerce%20Dataset.xlsx"
df = pd.read_excel(url, sheet_name="E Comm")   # the data is on the "E Comm" sheet

print(df.shape)
df.head()

missing = df.isnull().sum()
missing[missing > 0]

fixes = {
    "PreferredLoginDevice": {"Phone": "Mobile Phone"},
    "PreferredPaymentMode": {"CC": "Credit Card", "COD": "Cash on Delivery"},
    "PreferedOrderCat": {"Mobile": "Mobile Phone"},
}
df = df.replace(fixes)

for col in fixes:
    print(col, df[col].value_counts().to_dict())

cols_except_id = [c for c in df.columns if c != "CustomerID"]

print("Duplicate rows found:", df.duplicated(subset=cols_except_id).sum())
df = df.drop_duplicates(subset=cols_except_id, keep="first").reset_index(drop=True)

print("Rows after removing duplicates:", df.shape[0])
print("Churn rate now: {:.1f}%".format(df["Churn"].mean() * 100))

df.to_csv("ecommerce_churn_clean.csv", index=False)

